def transform_dataframe(df):
    """
    Transform a DataFrame by splitting tuple columns into separate value and confidence columns,
    and reordering columns according to a specific pattern.
    Ensures 'round_0' is kept if present.

    Args:
        df (pandas.DataFrame): Input DataFrame containing tuple columns for rounds

    Returns:
        pandas.DataFrame: Transformed DataFrame with split columns and specific ordering
    """
    # Create a copy to avoid modifying the original DataFrame
    df = df.copy()

    # Keep track of original columns to ensure non-round columns are preserved
    original_columns = df.columns.tolist()

    # List of columns to process (rounds 1-8)
    tuple_columns = [f'round_{i}' for i in range(1, 9)]

    # List to store columns to drop after processing
    cols_to_drop = []

    for col in tuple_columns:
        # Skip if column doesn't exist or is already split
        if col not in df.columns or f'{col}_value' in df.columns:
            continue

        # Convert string tuples to actual tuples and handle NaN values
        def parse_tuple(x):
            if pd.isna(x) or str(x).strip().lower() == 'nan':
                return (float('nan'), float('nan'))
            try:
                # Remove any whitespace and handle various formats
                x = str(x).replace(' ', '')
                # Handle cases where it might just be a number string
                if not (x.startswith('(') and x.endswith(')')):
                     try:
                         num_val = float(x)
                         return (num_val, float('nan')) # Assume no confidence if just a number
                     except ValueError:
                         return (float('nan'), float('nan'))

                return ast.literal_eval(x)
            except:
                return (float('nan'), float('nan'))

        # Create temporary column names
        value_col = f'{col}_value'
        conf_col = f'{col}_conf'

        # Apply the parsing function
        parsed_data = df[col].apply(parse_tuple)

        # Create two new columns
        df[value_col] = parsed_data.apply(lambda x: x[0])
        df[conf_col] = parsed_data.apply(lambda x: x[1] if len(x) > 1 else float('nan'))


        # Add original column to list to drop
        cols_to_drop.append(col)

    # Drop the original tuple columns that were processed
    df = df.drop(columns=[col for col in cols_to_drop if col in df.columns])


    # Rename the value columns back to original names (for rounds 1-8)
    rename_dict = {f'round_{i}_value': f'round_{i}' for i in range(1, 9)}
    df = df.rename(columns=rename_dict)

    # Define column groupings for final ordering
    # Ensure 'round_0' is included if it was in the original columns
    metadata_cols = ['question', 'choices', 'answer', 'level', 'subject']
    round_cols_order = [f'round_{i}' for i in range(0, 9)] # Include round_0 in desired order
    conf_cols_order = [f'round_{i}_conf' for i in range(1, 9)]

    # Create list of all columns in desired order
    final_cols = metadata_cols + round_cols_order + conf_cols_order

    # Ensure 'round_0' is not duplicated if it was already in metadata_cols and round_cols_order
    final_cols = list(dict.fromkeys(final_cols)) # Remove duplicates while preserving order

    # Include any original columns that are not in the defined groupings (e.g., batch_number)
    # and are not the original tuple columns that were dropped
    preserved_cols = [col for col in df.columns if col not in final_cols and col not in cols_to_drop]

    # Final column order: metadata, rounds (0-8), confidences (1-8), other preserved columns
    final_cols_ordered = [col for col in final_cols if col in df.columns] + preserved_cols


    # Reorder columns
    df = df[final_cols_ordered]

    return df

